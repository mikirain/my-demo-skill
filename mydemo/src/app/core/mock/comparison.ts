import { ComparableCheck, ComparisonCell, ComparisonRow, Dimension, JudgeStatus, RuleHit } from '../types';

const NAMES: Record<string, string> = { our: '我方', 'c-a': '竞对 A', 'c-b': '竞对 B', 'c-c': '竞对 C', 'c-d': '竞对 D' };

function cell(sourceId: string, display: string, status: JudgeStatus): ComparisonCell {
  return { sourceId, sourceName: NAMES[sourceId] ?? sourceId, display, status };
}

function rules(list: [string, string][]): RuleHit[] {
  return list.map(([rule, detail]) => ({ rule, detail }));
}

function cmp(p: Partial<ComparableCheck> = {}): ComparableCheck {
  return { level: true, unit: true, conditions: true, boundary: true, ...p };
}

interface ReqInput {
  text: string;
  mandatory: boolean;
  targetValue: string;
  unit: string;
  cond?: string;
}

function R(
  id: string,
  projectId: string,
  defKey: string,
  defLabel: string,
  req: ReqInput,
  dimension: Dimension,
  cells: ComparisonCell[],
  judged: JudgeStatus,
  reason: string,
  ruleHits: RuleHit[],
  comparable: ComparableCheck,
  clarify: string | undefined,
  weight: number,
): ComparisonRow {
  return {
    id,
    projectId,
    defKey,
    defLabel,
    requirement: {
      id: 'req-' + id,
      defKey,
      text: req.text,
      mandatory: req.mandatory,
      targetValue: req.targetValue,
      unit: req.unit,
      conditions: { note: req.cond },
    },
    dimension,
    mandatory: req.mandatory,
    cells,
    judged,
    reason,
    ruleHits,
    comparable,
    clarify,
    weight,
  };
}

